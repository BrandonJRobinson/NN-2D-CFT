class Ledger:
    def __init__(self, path: Path):
        self.df = pd.read_csv(path)

    def find(self, pattern: str, **eq):
        d = self.df
        for k, v in eq.items():
            d = d[d[k] == v]
        d = d[d["claim_id"].str.contains(pattern, regex=True, na=False)]
        return d

    def one(self, pattern: str, **eq):
        d = self.find(pattern, **eq)
        if d.empty:
            return None
        return d.iloc[0]

    def val(self, pattern: str, default="\\textsc{unresolved}", **eq):
        r = self.one(pattern, **eq)
        return default if r is None else str(r["value"])

    def unc(self, pattern: str, default="", **eq):
        r = self.one(pattern, **eq)
        return default if r is None else str(r["uncertainty"])


def num(x) -> str:
    """Render a ledger value as LaTeX maths without adding precision."""
    s = str(x).strip()
    if s in ("", "nan", "None"):
        return "\\textsc{unresolved}"
    try:
        v = float(s)
    except ValueError:
        return s.replace("_", "\\_")
    if v == 0:
        return "0"
    if 1e-3 <= abs(v) < 1e4:
        return f"{v:g}"
    mant, exp = f"{v:e}".split("e")
    return f"{float(mant):g}\\times10^{{{int(exp)}}}"


def cell(x) -> str:
    """Table cell: numeric values in math mode, everything else escaped text."""
    s = num(x)
    if s.startswith("\\textsc"):
        return s
    try:
        float(str(x).strip())
    except (TypeError, ValueError):
        return s
    return f"${s}$"


